#!/bin/sh
# Rufus Linux port: generate build/res_map.h (resource ID -> file in res/)
# from the upstream src/rufus.rc RCDATA table.
#
# Usage: tools/gen_res_map.sh [repo_root] [out_file]
set -e

ROOT="${1:-..}"
OUT="${2:-build/res_map.h}"
TMP="$(dirname "$OUT")/.res_ids.tmp"

mkdir -p "$(dirname "$OUT")"

# 1) name -> id from resource.h
awk '{ sub(/\r$/, "") } /^#define ID[A-Z0-9_]+[ \t]+[0-9]+/ { print $2, $3 }' "$ROOT/src/resource.h" > "$TMP"

# 2) join the rc RCDATA table against it. The rc file contains the resource
#    declarations twice: inside TEXTINCLUDE strings (with doubled quotes) and
#    as real statements. Handle both, and drop duplicates.
{
    echo "/* Generated by tools/gen_res_map.sh from src/rufus.rc - do not edit */"
    echo "typedef struct { unsigned id; const char* path; } res_map_entry_t;"
    echo "static const res_map_entry_t res_map[] = {"
    {
        sed -n 's/^[ \t]*"\(ID[A-Z0-9_]*\)[ \t]*RCDATA[ \t]*""\([^"]*\)"".*/\1 \2/p' "$ROOT/src/rufus.rc"
        sed -n 's/^[ \t]*\(ID[A-Z0-9_]*\)[ \t]*RCDATA[ \t]*"\([^"]*\)".*/\1 \2/p' "$ROOT/src/rufus.rc"
    } | awk '!seen[$1]++' | while read -r name path; do
        id="$(awk -v n="$name" '$1 == n { print $2; exit }' "$TMP")"
        [ -z "$id" ] && continue
        # rc paths are relative to src/ ("../res/..."): normalize to repo root
        rel="$(printf '%s' "$path" | sed 's|^\.\./||')"
        printf '    { %s, "%s" },\n' "$id" "$rel"
    done
    echo "};"
    echo "static const size_t res_map_count = sizeof(res_map)/sizeof(res_map[0]);"
} > "$OUT"

rm -f "$TMP"
echo "Generated $OUT"
