#!/bin/sh
# Rufus Linux port: generate build/res_ids.h (resource name -> numeric ID)
# from the upstream src/resource.h.
#
# Usage: tools/gen_res_ids.sh [src_dir] [out_file]
set -e

SRC_DIR="${1:-../src}"
OUT="${2:-build/res_ids.h}"

mkdir -p "$(dirname "$OUT")"

{
    echo "/* Generated by tools/gen_res_ids.sh from src/resource.h - do not edit */"
    echo "typedef struct { const char* name; int id; } res_id_entry_t;"
    echo "static const res_id_entry_t res_ids[] = {"
    awk '/^#define (MSG_[0-9]+|IDC_[A-Z0-9_]+|IDS_[A-Z0-9_]+|IDD_[A-Z0-9_]+|IDR_[A-Z0-9_]+|IDI_[A-Z0-9_]+)[ \t]+[0-9]+/ \
         { gsub(/\r/, "", $3); printf "    { \"%s\", %s },\n", $2, $3 }' "$SRC_DIR/resource.h"
    # Standard Windows dialog IDs appear in rufus.loc without being defined
    # in resource.h (they come from winuser.h)
    echo '    { "IDOK", 1 }, { "IDCANCEL", 2 }, { "IDABORT", 3 }, { "IDRETRY", 4 },'
    echo '    { "IDIGNORE", 5 }, { "IDYES", 6 }, { "IDNO", 7 }, { "IDCLOSE", 8 }, { "IDHELP", 9 },'
    echo "};"
    echo "static const size_t res_id_count = sizeof(res_ids)/sizeof(res_ids[0]);"
} > "$OUT"

echo "Generated $OUT"
